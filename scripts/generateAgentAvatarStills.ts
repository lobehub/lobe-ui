/**
 * Bakes the resting pose of every AgentAvatar shape into `src/AgentAvatar/stills.generated.ts`.
 * Building a shape's volume takes tens of milliseconds, so still avatars (and server rendering)
 * read this table and only animated avatars load the engine.
 *
 * Run `pnpm run generate:agent-avatar` after changing a shape or upgrading `open-bot-avatar`.
 */
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

import { avatarFrame, type Matrix } from 'open-bot-avatar';
import polygonClipping, { type MultiPolygon, type Ring } from 'polygon-clipping';

import { REST_YAW } from '../src/AgentAvatar/look';
import { getShapeDefinition, SHAPE_GEOMETRY } from '../src/AgentAvatar/shapes';
import { stillKey } from '../src/AgentAvatar/stillKey';
import type { AgentAvatarShape } from '../src/AgentAvatar/type';
import { flatten } from './agentAvatarPath';

type P = [number, number];

const TOLERANCE = 0.05;
const round = (value: number) => Math.round(value * 100) / 100;

const multiply = (m: Matrix, n: Matrix): Matrix => [
  m[0] * n[0] + m[2] * n[1],
  m[1] * n[0] + m[3] * n[1],
  m[0] * n[2] + m[2] * n[3],
  m[1] * n[2] + m[3] * n[3],
  m[0] * n[4] + m[2] * n[5] + m[4],
  m[1] * n[4] + m[3] * n[5] + m[5],
];

const toTransform = (m: Matrix) =>
  `matrix(${m.map((value, index) => Math.round(value * (index < 4 ? 10_000 : 100)) / (index < 4 ? 10_000 : 100)).join(' ')})`;

/** Ramer–Douglas–Peucker on an open polyline. */
const simplifyLine = (points: P[]): P[] => {
  if (points.length < 3) return points;
  const [ax, ay] = points[0];
  const [bx, by] = points.at(-1)!;
  const length = Math.hypot(bx - ax, by - ay) || 1;
  let [far, farIndex] = [0, 0];
  for (let index = 1; index < points.length - 1; index++) {
    const [x, y] = points[index];
    const distance = Math.abs((bx - ax) * (ay - y) - (ax - x) * (by - ay)) / length;
    if (distance > far) [far, farIndex] = [distance, index];
  }
  if (far <= TOLERANCE) return [points[0], points.at(-1)!];
  return [
    ...simplifyLine(points.slice(0, farIndex + 1)).slice(0, -1),
    ...simplifyLine(points.slice(farIndex)),
  ];
};

const simplifyRing = (ring: Ring): P[] => {
  const open = ring.slice(0, -1) as P[];
  const half = Math.floor(open.length / 2);
  return [
    ...simplifyLine(open.slice(0, half + 1)).slice(0, -1),
    ...simplifyLine([...open.slice(half), open[0]]).slice(0, -1),
  ];
};

const closed = (ring: P[]): Ring => [...ring, ring[0]];

/** The union of every body cross-section of a frame, as one path. */
const silhouette = (frame: ReturnType<typeof avatarFrame>) => {
  const paths = new Map(frame.paths.map((path) => [path.id, flatten(path.d)]));
  const sections: MultiPolygon[] = [];
  for (const item of frame.shapes) {
    if (item.kind !== 'slice') continue;
    const m = multiply(frame.root, item.matrix);
    const rings = paths
      .get(item.path)!
      .map((ring) =>
        closed(ring.map(([x, y]): P => [m[0] * x + m[2] * y + m[4], m[1] * x + m[3] * y + m[5]])),
      );
    // Holes wind the other way; an even-odd merge of the rings gives the same region.
    const [first, ...others] = rings.map((ring): MultiPolygon => [[ring]]);
    sections.push(others.length > 0 ? polygonClipping.xor(first, ...others) : first);
  }
  const [first, ...others] = sections;
  const union = polygonClipping.union(first, ...others);
  return union
    .flat()
    .map(
      (ring) =>
        `M${simplifyRing(ring)
          .map(([x, y]) => `${round(x)} ${round(y)}`)
          .join('L')}Z`,
    )
    .join('');
};

const entries = (Object.keys(SHAPE_GEOMETRY) as AgentAvatarShape[]).sort().map((shape) => {
  const frame = avatarFrame(getShapeDefinition(shape), {
    reducedMotion: true,
    view: { pitch: 0, yaw: REST_YAW },
  });
  const eye = (key: 'eye-0' | 'eye-1') => {
    const item = frame.shapes.find((candidate) => candidate.key === key)!;
    return toTransform(multiply(frame.root, item.matrix));
  };
  return [
    shape,
    {
      d: silhouette(frame),
      eyes: [eye('eye-0'), eye('eye-1')],
      key: stillKey(shape),
    },
  ] as const;
});

const output = `// Generated by scripts/generateAgentAvatarStills.ts. Do not edit.
import type { AgentAvatarStill } from './still';
import type { AgentAvatarShape } from './type';

export const AGENT_AVATAR_STILLS: Record<AgentAvatarShape, AgentAvatarStill> = {
${entries.map(([shape, still]) => `  ${shape}: ${JSON.stringify(still)},`).join('\n')}
};
`;

const target = resolve(import.meta.dirname, '../src/AgentAvatar/stills.generated.ts');
writeFileSync(target, output);
execFileSync('pnpm', ['exec', 'prettier', '--write', target], { stdio: 'ignore' });
console.log(`Baked ${entries.length} shapes, ${(output.length / 1024).toFixed(1)} KB`);
